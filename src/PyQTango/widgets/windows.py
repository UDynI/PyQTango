import inspect
import os.path as osp

from ..qt import QtCore, QtGui, QtWidgets, Qt, Signal, Slot, is_qt6, no_window_flags

import tango as PT


class TangoEvents2Qt(object):
    """ Class to implement translation from Tango events to Qt events
    """

    # Tango event signal
    tangoEvent = Signal(PT.EventData)

    def __init__(self):
        # Connect event signal
        self.tangoEvent.connect(self.__eventHandler)

    def eventCallback(self, event):
        """ Event callback
        """
        self.tangoEvent.emit(event)

    @Slot(PT.EventData)
    def __eventHandler(self, event):
        """ Event handling slot
        """
        self.on_TangoEvent(event)

    def on_TangoEvent(self, event):
        """ Event handling method (to be overridden in derived classes)
        """
        pass


class WindowScaling(object):
    """ Class to implement scaling functions for windows
    """
    def __init__(self):
        # Get app
        app = QtWidgets.QApplication.instance()

        # Qt6 (always) and Qt5 with AA_EnableHighDpiScaling (see
        # PyQTango.qt.make_application) already scale the UI: scaling it again
        # here would double it.
        if is_qt6() or app.testAttribute(Qt.ApplicationAttribute.AA_EnableHighDpiScaling):
            self.scaling = 1.0
            return

        # Get scaling factor for HiDPI
        design_dpi = 95
        current_dpi = app.primaryScreen().physicalDotsPerInch()
        self.scaling = float(current_dpi) / float(design_dpi)
        if self.scaling > 1.8:
            self.scaling = 1.8
        elif self.scaling < 1.1:
            self.scaling = 1.0

    def scaleUi(self, ui):
        """ Scale UI function to scale all widgets
            NOTE: compatible with GUIs generated by pyuic5
        """
        # Get minimum and maximum size and check if there are constrains in place
        constrain_min = False
        constrain_max = False
        min_sz = ui.minimumSize()
        max_sz = ui.maximumSize()
        old_sz = ui.size()

        if min_sz == old_sz:
            constrain_min = True
        if max_sz == old_sz:
            constrain_max = True

        # Setup font size and scaling on hidpi
        if self.scaling > 1.1:
            # Scale only if factor is more than 1.1
            self.scale_widget(ui, self.scaling)
            members = dir(self)
            for m in members:
                if issubclass(type(getattr(self, m)), QtWidgets.QWidget):
                    if getattr(self, m) == ui.parentWidget():
                        # Skip rescaling of parent widget, if saved inside current UI object
                        continue
                    # Scale widget
                    self.scale_widget(getattr(self, m), self.scaling)
                    if issubclass(type(getattr(self, m)), QtWidgets.QPushButton) and not getattr(self, m).icon().isNull():
                        # If widget is a pushbutton, scale also icons
                        ratio = 20.0 / 27.0
                        psz = getattr(self, m).size()
                        getattr(self, m).setIconSize(QtCore.QSize(int(psz.width() * ratio), int(psz.height() * ratio)))

        # Set maximum and minimum size if needed
        sz = ui.size()
        if constrain_min:
            ui.setMinimumSize(sz)
        if constrain_max:
            ui.setMaximumSize(sz)

    def scale_widget(self, widget, scaling):
        """ Generic widget scaling function
        """
        sz = widget.size()
        ps = widget.pos()
        widget.resize(int(sz.width() * scaling), int(sz.height() * scaling))
        widget.move(QtCore.QPoint(int(ps.x() * scaling), int(ps.y() * scaling)))


class QTangoMainWindow(TangoEvents2Qt, WindowScaling, QtWidgets.QMainWindow):
    """
    QTangoMainWindow(parent=None, flags=no_window_flags())

    Extension of QMainWindow to create Tango enabled GUIs. The class puts in
    place all that is needed to handle Tango events in Qt GUIs. Connect all
    Tango subscriptions to eventCallback(). Then overload in you derived class
    the method on_TangoEvent(self, event). The method will be supplied with
    EventData structures from Tango.

    NOTE: do not handle Tango events directly in Qt or you will get into
    trobles.

    scaleUi(main_window): this method handle GUI scaling for HiDpi screens. The
    system is designed to be used with GUIs compiled by pyuic5. Use this method
    the same way you use setupUi().

    setIcon(main_window, pixmap): this method set the window icon.

    getImage(image): search for an image and return a QPixmap. The image file
    is searched first in the icons subdirectory of the calling process
    main directory. If not found, it searches also the calling process main
    directory itself.

    """

    def __init__(self, parent=None, flags=no_window_flags()):
        """ Constructor
        """
        # Call parent constructor
        QtWidgets.QMainWindow.__init__(self, parent, flags)
        TangoEvents2Qt.__init__(self)
        WindowScaling.__init__(self)

    def setIcon(self, ui, pixmap):
        """ Set window icon
        """
        icon = QtGui.QIcon()
        icon.addPixmap(pixmap, QtGui.QIcon.Mode.Normal, QtGui.QIcon.State.Off)
        ui.setWindowIcon(icon)

    def getImage(self, image):
        frame = inspect.stack()[1]
        module = inspect.getmodule(frame[0])
        path = osp.abspath(osp.dirname(module.__file__))

        image_path = osp.join(path, 'icons', image)
        if not osp.isfile(image_path):
            image_path = osp.join(path, image)
            if not osp.isfile(image_path):
                return QtGui.QPixmap()

        return QtGui.QPixmap(osp.abspath(image_path))


class QTangoDialog(TangoEvents2Qt, WindowScaling, QtWidgets.QDialog):
    """ Same as QTangoMainWindow but for QDialogs
    """

    def __init__(self, parent=None, f=no_window_flags()):
        """ Constructor
        """
        # Call parent constructor
        QtWidgets.QDialog.__init__(self, parent, f)
        TangoEvents2Qt.__init__(self)
        WindowScaling.__init__(self)
